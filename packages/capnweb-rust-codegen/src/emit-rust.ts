import { createHash } from "node:crypto";

import { NameAllocator, toRustFieldName, toRustTypeName } from "./names.js";
import type {
  FunctionDeclaration,
  ObjectDeclaration,
  RustDeclaration,
  RustSchema,
  TargetDeclaration,
  TargetMember,
  TypeId,
  TypeRef,
  UnionDeclaration,
} from "./schema.js";

interface EmitContext {
  names: ReadonlyMap<TypeId, string>;
  kinds: ReadonlyMap<TypeId, RustDeclaration["kind"]>;
}

/** Emit ordinary Rust declarations from the semantic schema. */
export function emitRustSchema(schema: RustSchema): string {
  let context: EmitContext = {
    names: allocateTypeNames(schema.declarations),
    kinds: new Map(
      schema.declarations.map((declaration) => [declaration.id, declaration.kind])
    ),
  };
  let schemaHash = createHash("sha256")
    .update(JSON.stringify(schema))
    .digest("hex");
  let declarations = schema.declarations.map((declaration) =>
    emitDeclaration(declaration, context)
  );
  return [
    "// @generated by capnweb-rust-codegen. Do not edit.",
    `// Schema SHA-256: ${schemaHash}`,
    "",
    declarations.join("\n\n"),
    "",
  ].join("\n");
}

function allocateTypeNames(
  declarations: readonly RustDeclaration[]
): ReadonlyMap<TypeId, string> {
  let allocator = new NameAllocator();
  return new Map(
    declarations.map((declaration) => [
      declaration.id,
      allocator.allocate(toRustTypeName(declaration.sourceName)),
    ])
  );
}

function emitDeclaration(
  declaration: RustDeclaration,
  context: EmitContext
): string {
  switch (declaration.kind) {
    case "object":
      return emitObject(declaration, context);
    case "target":
      return emitCapability(declaration, context);
    case "function":
      return emitFunction(declaration, context);
    case "union":
      return emitUnion(declaration, context);
  }
}

function emitObject(
  declaration: ObjectDeclaration,
  context: EmitContext
): string {
  let name = requiredName(context, declaration.id);
  let pendingName = `Pending${name}`;
  let allocator = new NameAllocator();
  let fields = declaration.fields.map((field) => ({
    ...field,
    rustName: allocator.allocate(toRustFieldName(field.wireName)),
  }));
  let structFields = fields
    .map(
      (field) =>
        `    pub ${field.rustName}: ${renderOptionalType(field.type, field.optional, context)},`
    )
    .join("\n");
  let decodeFields = fields
    .map(
      (field) =>
        `            ${field.rustName}: <${renderOptionalType(field.type, field.optional, context)} as ::capnweb::FromCapnwebValue>::from_capnweb_value(\n` +
        "                fields\n" +
        `                    .remove(${rustString(field.wireName)})\n` +
        "                    .unwrap_or(::capnweb::CapnwebValue::Null),\n" +
        "            )?,"
    )
    .join("\n");
  let encodeFields = fields
    .map(
      (field) =>
        "        fields.insert(\n" +
        `            ${rustString(field.wireName)}.to_owned(),\n` +
        `            ::capnweb::IntoCapnwebValue::into_capnweb_value(self.${field.rustName})?,\n` +
        "        );"
    )
    .join("\n");
  let pendingFields = fields
    .map(
      (field) =>
        `    pub ${field.rustName}: ${renderPendingType(field.type, context)},`
    )
    .join("\n");
  let pendingInitializers = fields
    .map((field) => {
      let path = `promise.get(vec![${rustString(field.wireName)}.to_owned()])`;
      let value = wrapPending(field.type, path, context);
      let line = `            ${field.rustName}: ${value},`;
      if (line.length <= 100) return line;
      return `            ${field.rustName}: ${pendingConstructor(field.type, context)}(\n` +
        `                ${path},\n` +
        "            ),";
    })
    .join("\n");

  return `#[derive(Clone, Debug)]
pub struct ${name} {
${structFields}
}

impl ::capnweb::FromCapnwebValue for ${name} {
    fn from_capnweb_value(value: ::capnweb::CapnwebValue) -> ::capnweb::Result<Self> {
        let ::capnweb::CapnwebValue::Object(mut fields) = value else {
            return Err(::capnweb::Error::Type(format!(
                "expected object for ${name}, got {value:?}",
            )));
        };
        Ok(Self {
${decodeFields}
        })
    }
}

impl ::capnweb::IntoCapnwebValue for ${name} {
    fn into_capnweb_value(self) -> ::capnweb::Result<::capnweb::CapnwebValue> {
        let mut fields = ::std::collections::BTreeMap::new();
${encodeFields}
        Ok(::capnweb::CapnwebValue::Object(fields))
    }
}

pub struct ${pendingName} {
    inner: ::capnweb::TypedRpcPromise<${name}>,
${pendingFields}
}

impl ${pendingName} {
    fn new(promise: ::capnweb::RpcPromise) -> Self {
        Self {
${pendingInitializers}
            inner: ::capnweb::TypedRpcPromise::new(promise),
        }
    }
}

impl ::std::future::Future for ${pendingName} {
    type Output = ::capnweb::Result<${name}>;

    fn poll(
        mut self: ::std::pin::Pin<&mut Self>,
        context: &mut ::std::task::Context<'_>,
    ) -> ::std::task::Poll<Self::Output> {
        ::std::pin::Pin::new(&mut self.inner).poll(context)
    }
}`;
}

function emitCapability(
  declaration: TargetDeclaration,
  context: EmitContext,
  functionLike = false
): string {
  let name = requiredName(context, declaration.id);
  let pendingName = `Pending${name}`;
  let allocator = new NameAllocator();
  let members = declaration.members.map((member) => ({
    member,
    rustName: allocator.allocate(
      functionLike ? "call" : toRustFieldName(member.wireName)
    ),
  }));
  let resolvedMethods = members
    .map(({ member, rustName }) =>
      emitClientMethod(
        member,
        rustName,
        "self.inner",
        context,
        functionLike
      )
    )
    .join("\n\n");
  let pendingMethods = members
    .map(({ member, rustName }) =>
      emitClientMethod(
        member,
        rustName,
        "self.pipeline",
        context,
        functionLike
      )
    )
    .join("\n\n");
  let descriptorMembers = members
    .map(({ member }) => rustString(member.wireName))
    .join(", ");
  let descriptor = functionLike
    ? ""
    : `\n\nimpl ::capnweb::RpcInterfaceDescriptor for ${name} {\n` +
      "    fn has_member(wire_name: &str) -> bool {\n" +
      (members.length === 0
        ? "        false\n"
        : `        [${descriptorMembers}].contains(&wire_name)\n`) +
      "    }\n" +
      "}";

  return `#[derive(Clone, Debug)]
pub struct ${name} {
    inner: ::capnweb::RpcStub,
}${descriptor}

impl ${name} {
    pub fn new(inner: ::capnweb::RpcStub) -> Self {
        Self { inner }
    }

${indent(resolvedMethods, 4)}
}

impl ::capnweb::FromCapnwebValue for ${name} {
    fn from_capnweb_value(value: ::capnweb::CapnwebValue) -> ::capnweb::Result<Self> {
        match value {
            ::capnweb::CapnwebValue::Stub(stub) => Ok(Self::new(stub)),
            ::capnweb::CapnwebValue::Target(target) => Ok(Self::new(
                ::capnweb::RpcStub::from_value(::capnweb::CapnwebValue::Target(target)),
            )),
            other => Err(::capnweb::Error::Type(format!(
                "expected capability for ${name}, got {other:?}",
            ))),
        }
    }
}

impl ::capnweb::IntoCapnwebValue for ${name} {
    fn into_capnweb_value(self) -> ::capnweb::Result<::capnweb::CapnwebValue> {
        ::capnweb::IntoCapnwebValue::into_capnweb_value(self.inner)
    }
}

pub struct ${pendingName} {
    inner: ::capnweb::TypedRpcPromise<${name}>,
    pipeline: ::capnweb::RpcPromise,
}

impl ${pendingName} {
    fn new(promise: ::capnweb::RpcPromise) -> Self {
        Self {
            inner: ::capnweb::TypedRpcPromise::new(promise.clone()),
            pipeline: promise,
        }
    }

${indent(pendingMethods, 4)}
}

impl ::std::future::Future for ${pendingName} {
    type Output = ::capnweb::Result<${name}>;

    fn poll(
        mut self: ::std::pin::Pin<&mut Self>,
        context: &mut ::std::task::Context<'_>,
    ) -> ::std::task::Poll<Self::Output> {
        ::std::pin::Pin::new(&mut self.inner).poll(context)
    }
}`;
}

function emitFunction(
  declaration: FunctionDeclaration,
  context: EmitContext
): string {
  // The direct representation deliberately starts with an explicit call method.
  // A Deref-to-Fn facade can be layered on without changing its wire identity.
  let target: TargetDeclaration = {
    kind: "target",
    id: declaration.id,
    sourceName: declaration.sourceName,
    members: [
      {
        kind: "method",
        wireName: "call",
        parameters: declaration.parameters,
        ...(declaration.rest ? { rest: declaration.rest } : {}),
        returns: declaration.returns,
      },
    ],
  };
  return emitCapability(target, context, true);
}

function emitUnion(
  declaration: UnionDeclaration,
  context: EmitContext
): string {
  let name = requiredName(context, declaration.id);
  let literals = declaration.branches.filter(
    (branch): branch is Extract<TypeRef, { kind: "literal" }> =>
      branch.kind === "literal" && typeof branch.value === "string"
  );
  if (!declaration.nullable && literals.length === declaration.branches.length) {
    let allocator = new NameAllocator();
    let variants = literals.map((literal) => {
      let wireName = String(literal.value);
      return {
        wireName,
        rustName: allocator.allocate(toRustTypeName(wireName)),
      };
    });
    let declarations = variants
      .map((variant) => `    ${variant.rustName},`)
      .join("\n");
    let decodeArms = variants
      .map(
        (variant) =>
          `            ${rustString(variant.wireName)} => Ok(Self::${variant.rustName}),`
      )
      .join("\n");
    let encodeArms = variants
      .map(
        (variant) =>
          `            Self::${variant.rustName} => ${rustString(variant.wireName)},`
      )
      .join("\n");
    return `#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ${name} {
${declarations}
}

impl ::capnweb::FromCapnwebValue for ${name} {
    fn from_capnweb_value(value: ::capnweb::CapnwebValue) -> ::capnweb::Result<Self> {
        let ::capnweb::CapnwebValue::String(value) = value else {
            return Err(::capnweb::Error::Type(format!(
                "expected string for ${name}, got {value:?}",
            )));
        };
        match value.as_str() {
${decodeArms}
            other => Err(::capnweb::Error::Type(format!(
                "unknown ${name} value {other:?}",
            ))),
        }
    }
}

impl ::capnweb::IntoCapnwebValue for ${name} {
    fn into_capnweb_value(self) -> ::capnweb::Result<::capnweb::CapnwebValue> {
        let value = match self {
${encodeArms}
        };
        Ok(::capnweb::CapnwebValue::String(value.to_owned()))
    }
}`;
  }
  return `// This union is structurally ambiguous on the wire in v0.
pub type ${name} = ::capnweb::CapnwebValue;`;
}

function emitClientMethod(
  member: TargetMember,
  rustName: string,
  receiver: string,
  context: EmitContext,
  functionLike = false
): string {
  let parameterNames = new NameAllocator();
  let method = member.kind === "method" ? member : undefined;
  let parameters = (method?.parameters ?? []).map((parameter) => ({
    parameter,
    rustName: parameterNames.allocate(toRustFieldName(parameter.sourceName)),
  }));
  let restName = method?.rest ? parameterNames.allocate("rest") : undefined;
  let signature = parameters.map(
    ({ parameter, rustName }) =>
      `${rustName}: ${renderOptionalType(parameter.type, parameter.optional, context)}`
  );
  if (method?.rest && restName) {
    signature.push(`${restName}: Vec<${renderType(method.rest, context)}>`);
  }
  let returnType = renderPendingType(member.returns, context);
  let promise =
    member.kind === "getter"
      ? `${receiver}.get(vec![${rustString(member.wireName)}.to_owned()])`
      : emitCallExpression(
          member,
          receiver,
          parameters.map(({ rustName }) => rustName),
          restName,
          functionLike
        );
  let renderedParameters = signature.join(", ");
  return `pub fn ${rustName}(&self${renderedParameters ? `, ${renderedParameters}` : ""}) -> ${returnType} {
    let promise = ${promise};
    ${wrapPending(member.returns, "promise", context)}
}`;
}

function emitCallExpression(
  member: Extract<TargetMember, { kind: "method" }>,
  receiver: string,
  parameterNames: readonly string[],
  restName: string | undefined,
  functionLike: boolean
): string {
  if (member.kind !== "method") throw new Error("expected method");
  let initialArguments = parameterNames
    .map(
      (name) =>
        `::capnweb::IntoCapnwebValue::into_capnweb_value(${name})?`
    )
    .join(", ");
  let declaration = restName
    ? `            let mut arguments = vec![${initialArguments}];`
    : `            let arguments = vec![${initialArguments}];`;
  let restPush = restName
    ? `\n            for value in ${restName} {\n                arguments.push(::capnweb::IntoCapnwebValue::into_capnweb_value(value)?);\n            }`
    : "";
  let encodedArguments =
    parameterNames.length === 0 && !restName
      ? "let arguments: ::capnweb::Result<Vec<::capnweb::CapnwebValue>> = Ok(Vec::new());"
      : "let arguments = (|| -> ::capnweb::Result<Vec<::capnweb::CapnwebValue>> {\n" +
        `${declaration}${restPush}\n` +
        "            Ok(arguments)\n" +
        "        })();";
  return `{\n        ${encodedArguments}\n` +
    "        match arguments {\n" +
    `            Ok(arguments) => ${receiver}.call(\n` +
    `                ${functionLike ? "vec![]" : `vec![${rustString(member.wireName)}.to_owned()]`},\n` +
    "                ::capnweb::RpcPayload::from_app_params(::capnweb::CapnwebValue::Array(\n" +
    "                    arguments,\n" +
    "                )),\n" +
    "            ),\n" +
    "            Err(error) => ::capnweb::RpcPromise::rejected(error),\n" +
    "        }\n" +
    "    }";
}

function renderPendingType(type: TypeRef, context: EmitContext): string {
  if (type.kind === "named") {
    let kind = context.kinds.get(type.id);
    if (kind === "object" || kind === "target" || kind === "function") {
      return `Pending${requiredName(context, type.id)}`;
    }
  }
  return `::capnweb::TypedRpcPromise<${renderType(type, context)}>`;
}

function wrapPending(type: TypeRef, expression: string, context: EmitContext): string {
  return `${pendingConstructor(type, context)}(${expression})`;
}

function pendingConstructor(type: TypeRef, context: EmitContext): string {
  if (type.kind === "named") {
    let kind = context.kinds.get(type.id);
    if (kind === "object" || kind === "target" || kind === "function") {
      return `Pending${requiredName(context, type.id)}::new`;
    }
  }
  return "::capnweb::TypedRpcPromise::new";
}

function renderOptionalType(
  type: TypeRef,
  optional: boolean,
  context: EmitContext
): string {
  if (!optional || type.kind === "nullable") return renderType(type, context);
  return `Option<${renderType(type, context)}>`;
}

function renderType(type: TypeRef, context: EmitContext): string {
  switch (type.kind) {
    case "string":
      return "String";
    case "boolean":
      return "bool";
    case "number":
      return "f64";
    case "bigint":
      return "::capnweb::BigInt";
    case "void":
      return "()";
    case "null":
      return "Option<::capnweb::CapnwebValue>";
    case "literal":
      return typeof type.value === "string" ? "String" : typeof type.value === "boolean" ? "bool" : "f64";
    case "nullable":
      return `Option<${renderType(type.inner, context)}>`;
    case "array":
      return `Vec<${renderType(type.element, context)}>`;
    case "tuple": {
      let elements = type.elements.map((element) =>
        renderOptionalType(element.type, element.optional, context)
      );
      if (type.rest) throw new Error("variadic tuples are not implemented");
      return `(${elements.join(", ")}${elements.length === 1 ? "," : ""})`;
    }
    case "record":
      return `::std::collections::BTreeMap<String, ${renderType(type.value, context)}>`;
    case "named":
      return requiredName(context, type.id);
    case "promise":
      return `::capnweb::RpcPromise`;
    case "readableStream":
      return `::capnweb::RpcReadStream<${renderType(type.chunk, context)}>`;
    case "writableStream":
      return `::capnweb::RpcWriteSink<${renderType(type.chunk, context)}>`;
    case "union":
    case "dynamic":
      return "::capnweb::CapnwebValue";
    case "builtin":
      return BUILTIN_RUST_TYPES[type.name];
  }
}

function requiredName(context: EmitContext, id: TypeId): string {
  let name = context.names.get(id);
  if (!name) throw new Error(`Schema references missing declaration ${id}`);
  return name;
}

function rustString(value: string): string {
  return JSON.stringify(value)
    .replace(/\\b/g, "\\u{8}")
    .replace(/\\f/g, "\\u{c}");
}

function indent(value: string, spaces: number): string {
  let prefix = " ".repeat(spaces);
  return value
    .split("\n")
    .map((line) => (line ? `${prefix}${line}` : line))
    .join("\n");
}

const BUILTIN_RUST_TYPES = {
  arrayBuffer: "::capnweb::ArrayBuffer",
  dataView: "::capnweb::DataView",
  date: "::capnweb::Date",
  error: "::capnweb::RemoteError",
  headers: "::capnweb::Headers",
  url: "::url::Url",
  int8Array: "Vec<i8>",
  uint8Array: "Vec<u8>",
  uint8ClampedArray: "Vec<u8>",
  int16Array: "Vec<i16>",
  uint16Array: "Vec<u16>",
  int32Array: "Vec<i32>",
  uint32Array: "Vec<u32>",
  bigInt64Array: "Vec<i64>",
  bigUint64Array: "Vec<u64>",
  float32Array: "Vec<f32>",
  float64Array: "Vec<f64>",
} as const;
